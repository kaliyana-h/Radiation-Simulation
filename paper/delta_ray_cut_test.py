#!/usr/bin/env python3
"""Delta-ray production-cut paired A/B on the thin-wall kernel slab (PC run).

HYPOTHESIS (code review 2026-11-15, "delta rays at Q=1")
--------------------------------------------------------
Our dose-equivalent scorers (extensions/DoseEquivalentICRP.cc and twins) score each
step's energy deposit times Q(L), where L is the STEPPING particle's unrestricted LET
(G4EmCalculator::ComputeElectronicDEDX). Geant4 produces delta electrons above the
production cut as separate tracks. Their own LET is < 10 keV/um, so their energy is
scored at Q = 1. Under the ICRU convention, Q is a function of the ion's UNRESTRICTED
LET, so that energy should carry the ion's Q. The likely result:
  * absorbed dose is ~unchanged (the energy is still deposited, mostly nearby);
  * H, and so Q-bar, is biased LOW. A rough Bethe estimate is ~10-16% for HZE
    nodes (about 17% of a 1 GeV/n Fe ion's loss goes to deltas above a ~57 keV
    cut), small for protons.
This may account for part of the deep <Q> undershoot vs CRaTER (2.55 vs 3.5 @20 g/cm2)
and the direct-Si <Q> 3.95 vs 4.3.

DESIGN (paired, single variable)
--------------------------------
The production kernel slab is regenerated by templates.build_param_file. The physics
line is spliced exactly as paper/fragmentation_sensitivity.py splices it. Configs:
  ftfp     SHIPPED reference list FTFP_BERT_HP, untouched. This is the anchor to
           production only, NOT the A/B control: the TOPAS guide documents region
           cuts only for Geant4_Modular.
  modular  FTFP_BERT_HP rebuilt as modules (fragmentation_sensitivity._modular("g4ion")),
           default cuts. This is the A/B CONTROL.
  nodelta  the SAME modular list, plus a physics region "Tissue" holding every water
           organ shell, with CutForElectron = 100 cm there. Inside the phantom almost
           no delta ray is produced, so the ion deposits its full loss locally at its
           own Q. The wall and world keep the default cuts, so wall transport is
           identical. Gamma/positron cuts in the region are set explicitly to
           0.05 mm, the value the guide says the region assigns by default.
The ONLY difference between modular and nodelta is the electron cut inside the phantom.
Diagnostic arms (added 2026-11-17 after the first H+Fe run gave D nodelta/modular = 5.0,
i.e. the precondition FAILED):
  region   same region block, CutForElectron = 0.05 mm (= default) -> does the region
           ITSELF change D? (should be 1.00)
  cut1mm   CutForElectron = 1 mm (~350 keV in water) -> does D drift with the cut size?
Use --nodes H:4,Fe:5 to run only a few nodes with more seeds. The per-node table shows
D_cfg / D_modular (or vs the first config) and Q = I/D for every config.

Syntax was checked against the TOPAS user guide (Physics > Modular physics lists:
"s:Ge/MyComponent/AssignToRegionNamed", "d:Ph/Default/ForRegion/MyRegion/CutForElectron";
"CutForAllParticles does not have effect on physics regions") and against
examples/MVLinac (ForRegion/<R>/CutFor*) on 2026-11-17.
Cut clamp: Geant4 converts the range cut to an energy capped by the production-cut
high edge. Even a low 30 MeV edge sits far above the max delta energy for the bulk of
the GCR (Tmax ~3 MeV at 1 GeV/n, ~9 MeV at 2 GeV/n), so the clamp cannot hide the effect.

WHAT TO READ
------------
  D_eff  nodelta/modular ~ 1.00   (absorbed energy conserved; a few % redistribution
                                   between adjacent shells is allowed)
  Q-bar  nodelta/modular > 1      (the size of the scoring bias). Heavy nodes should
                                   move most and H nodes least. The per-node table
                                   shows this.
  If Q-bar does NOT move for the Fe nodes, the region cut did not take effect (or the
  hypothesis is wrong). Check topas.log before concluding either way.
TARGET-BLIND: no CAL refit, nothing is fitted. CRaTER/OLTARIS are NOT used here; the
result is a scorer-convention systematic to report, and changing the scorer is a user
decision.

Run it (PC; per-element 10-ion set, 62 nodes x seeds x configs):
    export TOPAS_G4_DATA_DIR=~/G4Data
    cd ~/topas
    .venv/bin/python paper/delta_ray_cut_test.py runs/delta54 --areal 54
Quick mechanistic check first (per-node ratios only, no valid folded number):
    .venv/bin/python paper/delta_ray_cut_test.py runs/delta54 --areal 54 --species H,Fe
Re-running is safe: a node whose organ CSVs already parse is skipped unless --force.
"""
from __future__ import annotations

import argparse
import csv
import os
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parent
for _p in (str(REPO_ROOT), str(HERE)):
    if _p not in sys.path:
        sys.path.insert(0, _p)

from lunarsim import dosimetry  # noqa: E402
from lunarsim.kernel_gen import config, templates  # noqa: E402
import fragmentation_sensitivity as fs  # noqa: E402  (shared kernel-slab machinery)

TOPAS_BIN = REPO_ROOT / "bin" / "topas"
CSV_PATH = HERE / "delta_ray_cut_test.csv"
COMPOSITION = "perelement"          # the SHIPPED 10-ion per-element kernel set
WALL_GEOMETRY = "slab"              # the production kernel geometry
REGION = "Tissue"
NODELTA_E_CUT = "100 cm"            # electron range cut inside the phantom
REGION_OTHER_CUT = "0.05 mm"        # guide's per-region default for unspecified particles
SEC_PER_YEAR = 3.15576e7


def region_cut_lines(shell_names: list[str], e_cut: str = NODELTA_E_CUT) -> list[str]:
    """Physics-region block putting every organ shell in REGION with a large e- cut."""
    L = ["# --- delta-ray test: organ shells in their own physics region ---"]
    for name in shell_names:
        L.append(f's:Ge/{templates._shell_component_name(name)}/AssignToRegionNamed'
                 f' = "{REGION}"')
    L.append(f"d:Ph/Default/ForRegion/{REGION}/CutForElectron = {e_cut}")
    L.append(f"d:Ph/Default/ForRegion/{REGION}/CutForGamma    = {REGION_OTHER_CUT}")
    L.append(f"d:Ph/Default/ForRegion/{REGION}/CutForPositron = {REGION_OTHER_CUT}")
    return L


def parse_nodes(spec: str, meta: dict):
    """'H:4,Fe:5' -> {('H', 4), ('Fe', 5)}; '' -> None (all nodes)."""
    if not spec.strip():
        return None
    out = set()
    for tok in spec.split(","):
        sp, _, idx = tok.strip().partition(":")
        if sp not in meta or not idx.isdigit() or int(idx) >= len(meta[sp]["nodes_pernuc_mev"]):
            raise SystemExit(f"bad --nodes entry {tok!r} (species in --species, valid index)")
        out.add((sp, int(idx)))
    return out


def selected(only, species: str, node: int) -> bool:
    return only is None or (species, node) in only


def config_block(cfg: str, shell_names: list[str]) -> list[str]:
    if cfg == "ftfp":
        return [fs._PHYS_TARGET]
    if cfg == "modular":
        return fs._modular("g4ion")
    if cfg == "nodelta":
        return fs._modular("g4ion") + region_cut_lines(shell_names)
    if cfg == "region":     # region exists, every cut = default -> isolates the region itself
        return fs._modular("g4ion") + region_cut_lines(shell_names, REGION_OTHER_CUT)
    if cfg == "cut1mm":     # intermediate electron cut (~350 keV in water)
        return fs._modular("g4ion") + region_cut_lines(shell_names, "1 mm")
    raise ValueError(f"unknown config {cfg!r}; choose from {CONFIGS}")


CONFIGS = ("ftfp", "modular", "nodelta", "region", "cut1mm")


def build_text(cfg: str, material: str, wall: float, species: str, node: int,
               seed: int, threads: int) -> str:
    """The production slab param file with this config's physics block spliced in."""
    text = templates.build_param_file(material, wall, species, node, seed,
                                      threads=threads, composition=COMPOSITION,
                                      wall_geometry=WALL_GEOMETRY)
    n = text.count(fs._PHYS_TARGET)
    if n != 1:
        raise RuntimeError(f"expected exactly one physics line {fs._PHYS_TARGET!r}, "
                           f"found {n}; templates.py physics emission changed.")
    shells = [s[0] for s in config.SHELLS]
    return text.replace(fs._PHYS_TARGET, "\n".join(config_block(cfg, shells)))


def _run_one(rundir: Path, cfg: str, material: str, wall: float, species: str,
             node: int, seed: int, threads: int, env: dict, organ_names: list[str],
             force: bool) -> bool:
    rundir.mkdir(parents=True, exist_ok=True)
    if not force and fs._organ_files_present(rundir, organ_names):
        return True
    (rundir / "run.txt").write_text(build_text(cfg, material, wall, species, node,
                                               seed, threads))
    with (rundir / "topas.log").open("w") as log:
        proc = subprocess.run([str(TOPAS_BIN), "run.txt"], cwd=rundir, env=env,
                              stdout=log, stderr=subprocess.STDOUT)
    if proc.returncode != 0 or not fs._organ_files_present(rundir, organ_names):
        print(f"      FAIL {cfg}/{species}/n{node}/s{seed} (rc={proc.returncode}); "
              f"see {rundir/'topas.log'}")
        return False
    return True


def ratio_and_err(a: float, sa: float, b: float, sb: float) -> tuple[float, float]:
    """a/b with first-order independent-error propagation (seeds differ per config)."""
    if b <= 0 or a <= 0:
        return float("nan"), float("nan")
    r = a / b
    return r, r * ((sa / a) ** 2 + (sb / b) ** 2) ** 0.5


def main(argv=None) -> None:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("outdir")
    p.add_argument("--material", default="aluminium")
    p.add_argument("--areal", type=float, default=54.0,
                   help="slab areal density g/cm^2 (default 54 = reference design)")
    p.add_argument("--configs", default="modular,nodelta",
                   help=f"comma list from {','.join(CONFIGS)} (default modular,nodelta; "
                        "add ftfp to tie the control to production)")
    p.add_argument("--species", default="all",
                   help="comma list or 'all' (a subset gives per-node ratios only)")
    p.add_argument("--seeds", type=int, default=2)
    p.add_argument("--threads", type=int, default=0)
    p.add_argument("--phi-mv", type=float, default=400.0)
    p.add_argument("--report-organ", default="mid")
    p.add_argument("--nodes", default="",
                   help="restrict to species:node-index pairs, e.g. 'H:4,Fe:5' "
                        "(diagnostic; folded numbers then NOT valid)")
    p.add_argument("--force", action="store_true")
    args = p.parse_args(argv)

    if not TOPAS_BIN.exists():
        raise SystemExit(f"TOPAS binary not found at {TOPAS_BIN}")
    env = dict(os.environ)
    if "TOPAS_G4_DATA_DIR" not in env:
        raise SystemExit("TOPAS_G4_DATA_DIR is unset: export TOPAS_G4_DATA_DIR=~/G4Data")
    cfgs = [c.strip() for c in args.configs.split(",") if c.strip()]
    bad = [c for c in cfgs if c not in CONFIGS]
    if bad:
        raise SystemExit(f"unknown config(s) {bad}; choose from {CONFIGS}")

    meta_all = config.species_for(COMPOSITION)
    if args.species == "all":
        meta, subset = meta_all, False
    else:
        want = [s.strip() for s in args.species.split(",") if s.strip()]
        badsp = [s for s in want if s not in meta_all]
        if badsp:
            raise SystemExit(f"unknown species {badsp}; choose from {list(meta_all)}")
        meta, subset = {s: meta_all[s] for s in want}, True
    only = parse_nodes(args.nodes, meta)
    if only is not None:
        subset = True
    organs = config.organs_from_reference()
    organ_names = [o for o, _ in organs]
    if args.report_organ not in organ_names:
        raise SystemExit(f"--report-organ must be one of {organ_names}")
    base = Path(args.outdir).resolve()
    base.mkdir(parents=True, exist_ok=True)

    n_runs = sum(1 for sn, m in meta.items() for j in range(len(m["nodes_pernuc_mev"]))
                 if selected(only, sn, j)) * args.seeds
    print("=" * 78)
    print("DELTA-RAY PRODUCTION-CUT A/B  (scorer-convention systematic; TARGET-BLIND)")
    print("=" * 78)
    print(f"  anchor   : {args.areal:g} g/cm^2 {args.material}, slab, composition={COMPOSITION}")
    print(f"  species  : {', '.join(meta)}"
          + ("   [SUBSET: folded numbers NOT valid, per-node ratios only]" if subset else ""))
    print(f"  configs  : {', '.join(cfgs)}   seeds/node {args.seeds}   phi {args.phi_mv:g} MV")
    print(f"  ~runs    : {n_runs} per config ({n_runs * len(cfgs)} total)\n")

    res = {}
    for cfg in cfgs:
        print(f"--- {cfg}")
        t0, ok, fail = time.time(), 0, 0
        for sname, m in meta.items():
            for j in range(len(m["nodes_pernuc_mev"])):
                if not selected(only, sname, j):
                    continue
                for seed in range(1, args.seeds + 1):
                    rd = fs._run_dir(base, cfg, sname, j, seed)
                    if _run_one(rd, cfg, args.material, args.areal, sname, j, seed,
                                args.threads, env, organ_names, args.force):
                        ok += 1
                    else:
                        fail += 1
            print(f"    {sname:>3}: done", flush=True)
        point = fs._collect_point(base, cfg, args.material, args.areal, args.seeds,
                                  meta, organs)
        fold = fs._fold_qbar(point, args.phi_mv, organs)
        res[cfg] = {"point": point, "fold": fold, "ok": ok, "fail": fail,
                    "wall_min": (time.time() - t0) / 60.0}
        print(f"    -> Q-bar_eff {fold['q_eff']:.3f}  (ok {ok}, fail {fail}, "
              f"{res[cfg]['wall_min']:.1f} min)\n")

    print("=" * 78)
    print("  SUMMARY (wT-weighted, production fold)")
    print("=" * 78)
    print(f"  {'config':<8} {'Q-bar_eff':>9} {'E mSv/yr':>9} {'D_eff mGy/yr':>13}")
    for cfg in cfgs:
        f = res[cfg]["fold"]
        print(f"  {cfg:<8} {f['q_eff']:>9.3f} {f['E_sv_s']*SEC_PER_YEAR*1e3:>9.1f} "
              f"{f['Deff_gy_s']*SEC_PER_YEAR*1e3:>13.3f}")
    if "modular" in res and "nodelta" in res:
        a, b = res["nodelta"]["fold"], res["modular"]["fold"]
        print(f"\n  nodelta / modular :  D_eff {a['Deff_gy_s']/b['Deff_gy_s']:.3f}   "
              f"E {a['E_sv_s']/b['E_sv_s']:.3f}   Q-bar {a['q_eff']/b['q_eff']:.3f}")
        print("  (expect D_eff ~1.00; the Q-bar ratio IS the delta-ray scoring bias)")
        if subset:
            print("  [SUBSET run: these folded ratios are NOT the kernel answer]")
    if "ftfp" in res and "modular" in res:
        print(f"  modular / ftfp    :  Q-bar "
              f"{res['modular']['fold']['q_eff']/res['ftfp']['fold']['q_eff']:.3f}"
              "  (control ~ production check)")

    org = args.report_organ
    ref = "modular" if "modular" in res else cfgs[0]
    print(f"\n  PER-NODE '{org}' organ.  D: absorbed vs '{ref}' (±1 sigma from seed scatter);"
          f"  Q: I/D")
    hdr = f"   {'sp':>3} {'E MeV/n':>8}"
    for cfg in cfgs:
        hdr += f"  {cfg + ' D':>16} {'Q':>6}"
    print(hdr)
    rows = []
    for sname, m in meta.items():
        for j, e in enumerate(m["nodes_pernuc_mev"]):
            if not selected(only, sname, j):
                continue
            Rr = res[ref]["point"]["species"][sname]
            line = f"   {sname:>3} {e:>8.0f}"
            for cfg in cfgs:
                Rc = res[cfg]["point"]["species"][sname]
                d, sd = Rc["R"][org]["D"][j], Rc["Rsem"][org]["D"][j]
                dr, dre = ratio_and_err(d, sd, Rr["R"][org]["D"][j], Rr["Rsem"][org]["D"][j])
                q = Rc["R"][org]["I"][j] / d if d > 0 else float("nan")
                line += f"  {dr:>9.3f}±{dre:<6.3f} {q:>6.2f}"
                rows.append({"config": cfg, "species": sname, "E_MeV_n": e, "organ": org,
                             "D_R": f"{d:.6g}", "D_Rsem": f"{sd:.6g}",
                             "D_vs_ref": f"{dr:.4f}", "D_vs_ref_err": f"{dre:.4f}",
                             "Qbar": f"{q:.4f}"})
            print(line)

    with open(CSV_PATH, "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["config", "areal_gcm2", "seeds", "phi_mv", "subset", "q_eff",
                    "E_mSv_yr", "Deff_mGy_yr", "runs_ok", "runs_fail"])
        for cfg in cfgs:
            f = res[cfg]["fold"]
            w.writerow([cfg, f"{args.areal:g}", args.seeds, f"{args.phi_mv:g}", subset,
                        f"{f['q_eff']:.4f}", f"{f['E_sv_s']*SEC_PER_YEAR*1e3:.2f}",
                        f"{f['Deff_gy_s']*SEC_PER_YEAR*1e3:.4f}",
                        res[cfg]["ok"], res[cfg]["fail"]])
        if rows:
            w.writerow([])
            w.writerow(list(rows[0]))
            for r in rows:
                w.writerow(list(r.values()))
    print(f"\n  wrote {CSV_PATH}")


if __name__ == "__main__":
    main()
